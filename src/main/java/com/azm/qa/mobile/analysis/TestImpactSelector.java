package com.azm.qa.mobile.analysis;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * The Java twin of the web framework's {@code test:changed} / {@code --only-changed}: reads
 * {@code git diff}, works out which test classes could plausibly be affected, and writes
 * {@code testng-impacted.xml} so CI can run a fast, targeted lane on a pull request instead of
 * the full suite.
 *
 * <p>Selection is deliberately conservative rather than clever: a changed screen or spec pulls
 * in only the test classes that reference it by name, but a changed file anywhere under
 * {@code core/} or {@code healing/} — foundational, used by every screen — falls back to the
 * full suite. An impact selector that under-selects and lets a real regression slip through
 * untested is worse than one that occasionally over-selects.
 */
public final class TestImpactSelector {

    private static final Logger log = LoggerFactory.getLogger(TestImpactSelector.class);
    private static final Path TEST_ROOT = Path.of("src", "test", "java");
    private static final Path SPECS_DIR = Path.of("specs");
    private static final Set<String> BROAD_IMPACT_PACKAGES = Set.of(
            "core" + java.io.File.separator, "healing" + java.io.File.separator);

    public Result select(String baseRef) {
        List<String> changedFiles = gitDiffNameOnly(baseRef);
        if (changedFiles.isEmpty()) {
            log.info("No changed files against {} -- nothing to select", baseRef);
            return new Result(List.of(), false, "no changes");
        }

        boolean broadImpact = changedFiles.stream()
                .anyMatch(f -> BROAD_IMPACT_PACKAGES.stream().anyMatch(f::contains));
        if (broadImpact) {
            List<String> allTestClasses = findAllTestClasses();
            return new Result(allTestClasses, true,
                    "a core/ or healing/ file changed -- these are used by every screen, so the full suite runs");
        }

        Set<String> signals = new LinkedHashSet<>();
        for (String file : changedFiles) {
            if (file.endsWith(".java")) {
                signals.add(simpleClassName(file));
            } else if (file.startsWith("specs" + java.io.File.separator) || file.startsWith("specs/")) {
                signals.add(featureNameToClassName(file) + "Test");
            }
        }

        List<String> impacted = new ArrayList<>();
        for (Path testFile : findAllTestFiles()) {
            String className = simpleClassNameFromPath(testFile);
            if (signals.contains(className)) {
                impacted.add(className);
                continue;
            }
            String content = readQuietly(testFile);
            if (signals.stream().anyMatch(content::contains)) {
                impacted.add(className);
            }
        }

        return new Result(impacted, false,
                impacted.size() + " test class(es) reference the " + changedFiles.size() + " changed file(s)");
    }

    public void writeSuiteXml(Result result, Path outputFile) {
        StringBuilder xml = new StringBuilder();
        xml.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        xml.append("<!DOCTYPE suite SYSTEM \"https://testng.org/testng-1.0.dtd\">\n");
        xml.append("<!-- Generated by TestImpactSelector -- ").append(escapeXml(result.reason())).append(" -->\n");
        xml.append("<suite name=\"ImpactedSuite\" verbose=\"1\">\n");
        xml.append("    <listeners>\n");
        xml.append("        <listener class-name=\"com.azm.qa.mobile.listeners.TestListener\"/>\n");
        xml.append("        <listener class-name=\"com.azm.qa.mobile.base.RetryTransformer\"/>\n");
        xml.append("    </listeners>\n");
        xml.append("    <test name=\"Impacted\">\n");
        xml.append("        <classes>\n");
        for (String className : result.impactedClasses()) {
            String qualified = qualifyClassName(className);
            if (qualified != null) {
                xml.append("            <class name=\"").append(qualified).append("\"/>\n");
            }
        }
        xml.append("        </classes>\n");
        xml.append("    </test>\n");
        xml.append("</suite>\n");

        try {
            Files.writeString(outputFile, xml.toString(), StandardCharsets.UTF_8);
            log.info("Wrote {} ({} class(es)) -- {}", outputFile, result.impactedClasses().size(), result.reason());
        } catch (IOException e) {
            throw new UncheckedIOException("Could not write " + outputFile, e);
        }
    }

    private List<String> gitDiffNameOnly(String baseRef) {
        Process process;
        try {
            // redirectErrorStream(true) is load-bearing, not cosmetic: an unresolvable ref (no
            // git repo yet, a shallow clone, a typo'd ref) makes git write a large usage/help
            // block to STDERR. Reading only stdout while nobody drains stderr is the classic
            // ProcessBuilder deadlock -- the child blocks writing to a full pipe, this thread
            // blocks reading the other one waiting for an EOF that can now never come. Merging
            // the streams means one read loop drains both.
            process = new ProcessBuilder("git", "diff", "--name-only", baseRef)
                    .redirectErrorStream(true)
                    .start();
        } catch (IOException e) {
            log.warn("Could not start git ({}) -- treating as no changes", e.getMessage());
            return List.of();
        }

        String output;
        boolean finished;
        try {
            output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            finished = process.waitFor(30, java.util.concurrent.TimeUnit.SECONDS);
        } catch (IOException e) {
            log.warn("Could not read git's output ({}) -- treating as no changes", e.getMessage());
            process.destroyForcibly();
            return List.of();
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            process.destroyForcibly();
            return List.of();
        }

        if (!finished) {
            log.warn("git diff against '{}' did not exit within 30s -- killing it and treating as no changes", baseRef);
            process.destroyForcibly();
            return List.of();
        }
        if (process.exitValue() != 0) {
            log.info("git diff against '{}' exited {} (likely an unresolvable ref) -- treating as no changes",
                    baseRef, process.exitValue());
            return List.of();
        }
        return output.lines().filter(l -> !l.isBlank()).toList();
    }

    private List<String> findAllTestClasses() {
        return findAllTestFiles().stream().map(this::simpleClassNameFromPath).toList();
    }

    private List<Path> findAllTestFiles() {
        if (!Files.isDirectory(TEST_ROOT)) {
            return List.of();
        }
        try (var stream = Files.walk(TEST_ROOT)) {
            return stream.filter(p -> p.toString().endsWith(".java")).toList();
        } catch (IOException e) {
            throw new UncheckedIOException("Could not walk " + TEST_ROOT, e);
        }
    }

    private String simpleClassNameFromPath(Path javaFile) {
        String name = javaFile.getFileName().toString();
        return name.substring(0, name.length() - ".java".length());
    }

    private String simpleClassName(String filePath) {
        int lastSlash = Math.max(filePath.lastIndexOf('/'), filePath.lastIndexOf('\\'));
        String fileName = filePath.substring(lastSlash + 1);
        return fileName.endsWith(".java") ? fileName.substring(0, fileName.length() - 5) : fileName;
    }

    private String featureNameToClassName(String specPath) {
        int lastSlash = Math.max(specPath.lastIndexOf('/'), specPath.lastIndexOf('\\'));
        String fileName = specPath.substring(lastSlash + 1).replace(".md", "");
        StringBuilder out = new StringBuilder();
        for (String word : fileName.split("[^A-Za-z0-9]+")) {
            if (!word.isEmpty()) {
                out.append(Character.toUpperCase(word.charAt(0))).append(word.substring(1).toLowerCase(Locale.ROOT));
            }
        }
        return out.toString();
    }

    private String readQuietly(Path file) {
        try {
            return Files.readString(file, StandardCharsets.UTF_8);
        } catch (IOException e) {
            return "";
        }
    }

    /** Best-effort: assumes generated tests live under com.azm.qa.mobile.generated and hand-written under a few known packages. */
    private String qualifyClassName(String simpleName) {
        List<Path> matches = findAllTestFiles().stream()
                .filter(p -> simpleClassNameFromPath(p).equals(simpleName))
                .toList();
        if (matches.isEmpty()) {
            return null;
        }
        Path relative = TEST_ROOT.relativize(matches.get(0));
        String withoutExtension = relative.toString().replace(".java", "");
        return withoutExtension.replace(java.io.File.separatorChar, '.');
    }

    private static String escapeXml(String value) {
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

    public record Result(List<String> impactedClasses, boolean fullSuiteFallback, String reason) {
    }
}
